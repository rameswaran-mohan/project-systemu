"""E2 — what ``systemu-launcher.exe`` actually runs (SPEC §14 E2).

The shipped ``{app}\\systemu-launcher.exe`` is a tiny self-locating stub (its
source is generated by :mod:`systemu.winpkg.build_step`). All it does is resolve
``{app}\\env\\pythonw.exe`` **relative to its own file**, export
``SYSTEMU_INSTALL_ROOT``, and run this module. Everything a launcher is expected
to decide is decided here, in Python, where it can be tested.

Why the stub does the resolving instead of a pip/distlib ``.exe`` shim: a
distlib launcher stub resolves a RELATIVE shebang through ``SearchPath()``,
which searches the **current directory** and ``PATH`` — not the directory the
.exe lives in. That was measured, not assumed: a stub with ``#!env\\python.exe``
launched a completely different ``env\\python.exe`` that happened to sit in the
CWD. A launcher that silently runs the wrong interpreter is worse than one that
refuses, so the stub uses its own module path instead.

Three jobs were named on this launcher when E2 was written:

  * start the daemon if it is not already up,
  * open the dashboard,
  * host the R-P7 global summon hotkey.

**The third one is not built.** There is no hotkey implementation anywhere in
this repo — ``platform_profile()`` reports that the *platform* can host a global
hotkey, which is a different claim from systemu having one. So
:func:`hotkey_host_status` reports it absent with a named reason and
``--hotkey`` exits non-zero. A launcher that swallowed ``--hotkey`` and silently
opened the dashboard instead would read as a working feature (PAR-1: a missing
capability is a visible fact, never a mystery). The installer script says the
same thing where it ships this .exe, so the two cannot tell different stories.
"""

from __future__ import annotations

import argparse
import os
import sys
import webbrowser
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Optional, Sequence

from .layout import ENV_DIRNAME, InstallLayout, literal_layout, resolve_layout

#: Set on the child process by the .exe stub: the directory the stub lives in,
#: which IS the install root ({app}). Named here so the generated stub and this
#: module cannot drift — :mod:`systemu.winpkg.build_step` renders the stub from
#: this constant and the packaging test pins the pair.
INSTALL_ROOT_ENV_VAR = "SYSTEMU_INSTALL_ROOT"

#: Where the runtime reads the vault from (``sharing_on.config.Config.from_env``).
VAULT_DIR_ENV_VAR = "SYSTEMU_VAULT_DIR"

DEFAULT_DASHBOARD_PORT = 8765

ACTION_OPEN = "open"
ACTION_FIRST_RUN = "first-run"
ACTION_HOTKEY = "hotkey"
ACTION_STATUS = "status"

#: Exit code for "you asked for something this build does not have".
EXIT_NOT_BUILT = 4


class LauncherRefused(Exception):
    """The launcher would not proceed. Nothing was started."""


@dataclass(frozen=True)
class LauncherResult:
    action: str
    exit_code: int
    daemon_was_running: Optional[bool] = None
    daemon_started: bool = False
    dashboard_url: Optional[str] = None
    opened_dashboard: bool = False
    notes: tuple = field(default=())


# ── where am I installed? ────────────────────────────────────────────────────

def resolve_install_layout(
    root: Optional[os.PathLike | str] = None,
    *,
    environ: Optional[dict] = None,
    prefix: Optional[os.PathLike | str] = None,
) -> InstallLayout:
    """Resolve the layout of the install this launcher belongs to.

    Order, most-trusted first:

    1. an explicit ``root`` (what a caller/test passes),
    2. ``%SYSTEMU_INSTALL_ROOT%`` — exported by the .exe stub from its OWN
       directory, so it is correct even when the CWD is somewhere else,
    3. ``sys.prefix``'s parent, but ONLY when the prefix is literally the
       ``env`` directory of an install. In a dev checkout ``sys.prefix`` is a
       virtualenv whose parent is meaningless, so the check is a real one and
       not a guess,
    4. the ordinary ``%LOCALAPPDATA%\\systemu`` resolution.
    """
    env = os.environ if environ is None else environ

    if root:
        return literal_layout(Path(root))

    from_env = (env.get(INSTALL_ROOT_ENV_VAR) or "").strip()
    if from_env:
        return literal_layout(Path(from_env))

    prefix_path = Path(sys.prefix if prefix is None else prefix)
    if prefix_path.name == ENV_DIRNAME:
        return literal_layout(prefix_path.parent)

    return resolve_layout(environ=env)


# ── the capability that does not exist ───────────────────────────────────────

def hotkey_host_status() -> dict:
    """Honest status for the R-P7 global summon hotkey.

    ``available`` is False and stays False until something actually registers a
    hotkey. Nothing in this repo does: there is no ``RegisterHotKey`` call, no
    message loop, and no quick-task surface for a hotkey to summon.
    """
    return {
        "id": "hotkey_host",
        "label": "Global summon hotkey (R-P7)",
        "available": False,
        "reason": (
            "R-P7 is not built: no hotkey is registered anywhere in this "
            "build, and there is no quick-task surface for one to summon."
        ),
    }


# ── actions ──────────────────────────────────────────────────────────────────

def _default_daemon_status(vault_dir: str) -> Optional[bool]:
    from systemu.scheduler.daemon import get_status

    return bool(get_status(vault_dir).get("running"))


def _default_start_daemon(vault_dir: str, port: int) -> None:
    from sharing_on.config import Config
    from systemu.scheduler.daemon import start_daemon
    from systemu.vault.vault import Vault

    config = Config.from_env()
    start_daemon(
        vault_dir=vault_dir,
        config=config,
        vault=Vault(vault_dir),
        port=port,
    )


def dashboard_url(port: int = DEFAULT_DASHBOARD_PORT) -> str:
    """Loopback only. The dashboard is not bound to a routable address here and
    this launcher must never imply that it is."""
    return f"http://127.0.0.1:{port}"


def point_runtime_at_the_sibling_vault(
    layout: InstallLayout, *, environ: Optional[dict] = None
) -> str:
    """Export ``SYSTEMU_VAULT_DIR`` as the install's SIBLING vault.

    This is the runtime half of the AC2/AC3 invariant; the installer half is
    the ``uninsneveruninstall`` ``[Dirs]`` entry for ``{app}\\vault`` in
    ``packaging/windows/systemu.iss``. Without this export the runtime
    (``systemu.runtime.vault_root.resolve_vault_root``) falls back to the
    RELATIVE default ``systemu/vault``, resolved against the CWD. From the .exe
    stub (CWD = ``{app}``) that is ``{app}\\systemu\\vault`` - a directory the
    installer neither pins nor names in its uninstall notice. From a CWD inside
    ``env`` it is a vault inside ``env``, which an upgrade renames to
    ``env.old`` and deletes (:func:`~systemu.winpkg.lifecycle.perform_upgrade`),
    and no amount of care there would help, because it would be deleting the
    right directory: the vault would genuinely be in there.
    ``tests/test_e2_installer_vault_pin.py`` pins this end to end through the
    real resolver.

    An operator override already in the environment wins (setdefault).
    """
    env = os.environ if environ is None else environ
    existing = (env.get(VAULT_DIR_ENV_VAR) or "").strip()
    if existing:
        return existing
    env[VAULT_DIR_ENV_VAR] = str(layout.vault_dir)
    return env[VAULT_DIR_ENV_VAR]


def launch(
    action: str = ACTION_OPEN,
    *,
    layout: InstallLayout,
    port: int = DEFAULT_DASHBOARD_PORT,
    environ: Optional[dict] = None,
    daemon_status: Optional[Callable[[str], Optional[bool]]] = None,
    start_daemon: Optional[Callable[[str, int], None]] = None,
    open_url: Optional[Callable[[str], bool]] = None,
) -> LauncherResult:
    """Perform one launcher action. Every effect is injected so this is testable
    without starting a daemon or opening a browser."""
    notes: list = []

    if action == ACTION_HOTKEY:
        status = hotkey_host_status()
        return LauncherResult(
            action=ACTION_HOTKEY,
            exit_code=EXIT_NOT_BUILT,
            notes=(status["reason"],),
        )

    vault_dir = point_runtime_at_the_sibling_vault(layout, environ=environ)

    if action == ACTION_STATUS:
        notes.append(f"install root: {layout.root}")
        notes.append(f"vault: {vault_dir}")
        notes.append(
            "vault is a sibling of the environment: "
            f"{layout.vault_is_outside_env()}"
        )
        notes.append(f"hotkey host: {hotkey_host_status()['reason']}")
        return LauncherResult(
            action=ACTION_STATUS,
            exit_code=0,
            dashboard_url=dashboard_url(port),
            notes=tuple(notes),
        )

    status_fn = daemon_status or _default_daemon_status
    start_fn = start_daemon or _default_start_daemon
    open_fn = open_url or webbrowser.open

    was_running = status_fn(vault_dir)
    started = False
    if not was_running:
        start_fn(vault_dir, port)
        started = True
        notes.append("started the systemu daemon")
    else:
        notes.append("the systemu daemon was already running")

    if action == ACTION_FIRST_RUN:
        # Say what actually happens. The dashboard redirects a fresh install to
        # /welcome (onboarding_gate), and that wizard does NOT take the provider
        # key in the browser — it asks the operator to put OPENROUTER_API_KEY in
        # .env and click Re-check. systemu.winpkg.first_run, the E2 key-entry
        # module, has no caller outside its own test, so this launcher has
        # nothing to hand a key to and does not pretend otherwise.
        notes.append(
            "first run: the dashboard redirects to /welcome for setup; the "
            "provider key is set by putting OPENROUTER_API_KEY in .env, not by "
            "typing it here"
        )

    url = dashboard_url(port)
    opened = bool(open_fn(url))
    if not opened:
        notes.append(f"could not open a browser; go to {url} yourself")

    return LauncherResult(
        action=action,
        exit_code=0,
        daemon_was_running=was_running,
        daemon_started=started,
        dashboard_url=url,
        opened_dashboard=opened,
        notes=tuple(notes),
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="systemu-launcher",
        description="Start the systemu daemon and open the dashboard.",
    )
    parser.add_argument("--root", default=None,
                        help="install root; the .exe stub exports it as "
                             f"%{INSTALL_ROOT_ENV_VAR}%")
    parser.add_argument("--port", type=int, default=DEFAULT_DASHBOARD_PORT)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--first-run", dest="action", action="store_const",
                       const=ACTION_FIRST_RUN,
                       help="post-install run: start up and land on setup")
    group.add_argument("--hotkey", dest="action", action="store_const",
                       const=ACTION_HOTKEY,
                       help="host the R-P7 global summon hotkey (NOT BUILT - "
                            "this exits non-zero and says so)")
    group.add_argument("--status", dest="action", action="store_const",
                       const=ACTION_STATUS,
                       help="print what this install resolved to and stop")
    parser.set_defaults(action=ACTION_OPEN)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    layout = resolve_install_layout(args.root)
    result = launch(args.action, layout=layout, port=args.port)
    for note in result.notes:
        stream = sys.stderr if result.exit_code else sys.stdout
        print(note, file=stream)
    return result.exit_code


if __name__ == "__main__":       # pragma: no cover
    raise SystemExit(main())
